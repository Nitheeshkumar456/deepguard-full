# metrics.py
"""Calculate evaluation metrics for DeepGuard AI model.

Reads the CSV generated by `evaluate.py` (located in `ai/evaluation/results/`
and computes Accuracy, Precision, Recall, F1‑score, Confusion Matrix and,
if both classes are present, ROC‑AUC.

Usage:
    python metrics.py
"""

import csv
from pathlib import Path

import numpy as np
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    roc_auc_score,
)

RESULTS_DIR = Path(__file__).parent / "results"
CSV_PATH = RESULTS_DIR / "evaluation_report.csv"

if not CSV_PATH.is_file():
    raise FileNotFoundError(f"Evaluation report not found at {CSV_PATH}")

# Load data
labels = []          # ground‑truth (0 or 1)
preds = []           # predicted class (0 or 1)
prob_fake = []       # probability for class 1 (fake)

with open(CSV_PATH, newline="", encoding="utf-8") as f:
    reader = csv.DictReader(f)
    for row in reader:
        # Skip rows where inference failed
        if row["predicted"] == "" or row["predicted"] is None:
            continue
        labels.append(int(row["ground_truth"]))
        preds.append(int(row["predicted"]))
        prob = row.get("prob_fake")
        prob_fake.append(float(prob) if prob not in ("", None) else np.nan)

labels = np.array(labels)
preds = np.array(preds)
prob_fake = np.array(prob_fake, dtype=float)

# Basic metrics (require at least one sample)
accuracy = accuracy_score(labels, preds)
precision = precision_score(labels, preds, zero_division=0)
recall = recall_score(labels, preds, zero_division=0)
f1 = f1_score(labels, preds, zero_division=0)
conf_mat = confusion_matrix(labels, preds)

print("=== Evaluation Metrics ===")
print(f"Accuracy   : {accuracy:.4f}")
print(f"Precision  : {precision:.4f}")
print(f"Recall     : {recall:.4f}")
print(f"F1‑score   : {f1:.4f}")
print("Confusion Matrix (rows = true, cols = pred):")
print(conf_mat)

# ROC‑AUC – only if both classes appear in ground truth
if len(np.unique(labels)) == 2 and not np.isnan(prob_fake).all():
    roc_auc = roc_auc_score(labels, prob_fake)
    print(f"ROC‑AUC   : {roc_auc:.4f}")
else:
    print("ROC‑AUC   : N/A (only one class present or missing probabilities)")
